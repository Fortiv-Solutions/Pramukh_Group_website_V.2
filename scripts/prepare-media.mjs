/**
 * Builds /public/media from the asset map in media.config.mjs and writes
 * src/content/media.generated.ts with dimensions and blur placeholders.
 *
 *   npm run media            process anything missing or outdated
 *   npm run media -- --force rebuild everything
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { SOURCE_DIR, OUTPUT_DIR, images, videos, frames } from "./media.config.mjs";

const root = process.cwd();
const force = process.argv.includes("--force");
const resolveSource = (p) => path.join(root, p.startsWith(".media-cache") ? p : path.join(SOURCE_DIR, p));
const isStale = (src, out) => force || !existsSync(out) || statSync(out).mtimeMs < statSync(src).mtimeMs;
const ffmpeg = (args) => execFileSync("ffmpeg", ["-v", "error", "-y", ...args], { stdio: "inherit" });

mkdirSync(path.join(root, ".media-cache"), { recursive: true });
mkdirSync(path.join(root, OUTPUT_DIR), { recursive: true });

for (const f of frames) {
  const src = resolveSource(f.source);
  const out = path.join(root, f.out);
  if (!isStale(src, out)) continue;
  console.log(`frame  ${f.out}`);
  const vf = f.crop ? ["-vf", `crop=${f.crop}`] : [];
  ffmpeg(["-ss", String(f.time), "-i", src, "-frames:v", "1", ...vf, "-q:v", "1", out]);
}

for (const v of videos) {
  const src = resolveSource(v.source);
  const duration = (v.end - v.start).toFixed(3);
  for (const o of v.outputs) {
    const out = path.join(root, OUTPUT_DIR, `${v.key}${o.suffix}.mp4`);
    if (!isStale(src, out)) continue;
    console.log(`video  ${path.relative(root, out)}`);
    const scale = `${o.crop ? `crop=${o.crop},` : ""}scale=${o.width}:-2:flags=lanczos,fps=30`;
    const filter = v.pingPong
      ? `[0:v]${scale},split[a][b];[b]reverse[r];[a][r]concat=n=2:v=1:a=0,format=yuv420p[v]`
      : `[0:v]${scale},format=yuv420p[v]`;
    ffmpeg([
      "-ss", String(v.start), "-t", duration, "-i", src,
      "-filter_complex", filter, "-map", "[v]", "-an",
      "-c:v", "libx264", "-preset", "slow", "-crf", String(o.crf), "-profile:v", "high", "-tune", "film",
      ...(o.maxrate ? ["-maxrate", o.maxrate, "-bufsize", `${parseFloat(o.maxrate) * 2}M`] : []),
      "-movflags", "+faststart", out,
    ]);
  }
}

const manifest = {};
for (const img of images) {
  const src = resolveSource(img.source);
  if (!existsSync(src)) throw new Error(`Missing source for ${img.key}: ${img.source}`);
  const file = `${img.key.replace(/\//g, "-")}.jpg`;
  const out = path.join(root, OUTPUT_DIR, file);
  if (isStale(src, out)) {
    console.log(`image  ${file}`);
    await sharp(src)
      .rotate()
      .resize({ width: img.width, withoutEnlargement: true })
      .jpeg({ quality: 84, mozjpeg: true, chromaSubsampling: "4:4:4" })
      .toFile(out);
  }
  const { width, height } = await sharp(out).metadata();
  const blur = await sharp(out).resize(16).blur(1).jpeg({ quality: 50 }).toBuffer();
  manifest[img.key] = {
    src: `/media/${file}`,
    width,
    height,
    alt: img.alt,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
  };
}

const ts = `// Generated by scripts/prepare-media.mjs — do not edit by hand.
// Edit scripts/media.config.mjs and run \`npm run media\` instead.
export const mediaManifest = ${JSON.stringify(manifest, null, 2)} as const;
`;
writeFileSync(path.join(root, "src/content/media.generated.ts"), ts);
console.log(`\n${Object.keys(manifest).length} images, ${videos.length} video set(s) ready.`);
